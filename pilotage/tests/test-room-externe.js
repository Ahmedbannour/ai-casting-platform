// Le chef de room invite une personne qui n'a pas encore de compte : il choisit son rôle, obtient un lien ;
// elle crée son compte et arrive directement dans la room. Comptes recette.*@exemple.tn effacés ensuite.
const { chromium } = require('playwright-core');
const fs = require('fs'), path = require('path');
const QA = JSON.parse(fs.readFileSync(path.join(__dirname, '.recette-admin.json'), 'utf8'));
const API = 'http://localhost:8080/api', BASE = 'http://localhost:4200', OUT = path.join(__dirname, '..', 'nav');
const j = async (url, opt = {}, tk) => { const r = await fetch(API + url, { ...opt, headers: { 'Content-Type': 'application/json', ...(tk ? { Authorization: 'Bearer ' + tk } : {}) } }); const t = await r.text(); try { return { s: r.status, b: JSON.parse(t) }; } catch { return { s: r.status, b: t }; } };
const ok = (c, m) => { if (!c) throw new Error('ÉCHEC : ' + m); console.log('OK  ' + m); };
(async () => {
  const adm = (await j('/auth/login', { method: 'POST', body: JSON.stringify({ email: QA.email, password: QA.password }) })).b.accessToken;
  const st = Date.now(), today = new Date().toISOString().slice(0, 10);
  const o = (await j('/admin/agencies', { method: 'POST', body: JSON.stringify({ name: `Recette Prod Room ${st}`, contractStart: today, kind: 'BOITE_PROD' }) }, adm)).b.id;
  const prod = { email: `recette.roomext.${st}@exemple.tn`, pw: 'Rec3tte-' + Math.random().toString(36).slice(2, 10) + '!' };
  await j('/admin/agents', { method: 'POST', body: JSON.stringify({ email: prod.email, firstName: 'Hédi', lastName: 'Recette', role: 'BOITE_PROD', agencyId: o, password: prod.pw }) }, adm);
  const tk = (await j('/auth/login', { method: 'POST', body: JSON.stringify({ email: prod.email, password: prod.pw }) })).b.accessToken;
  const pr = await j('/projects', { method: 'POST', body: JSON.stringify({ title: 'Recette Room Externe ' + st, type: 'PUBLICITE' }) }, tk);
  if (pr.s >= 300) throw new Error('projet ' + pr.s + ' ' + JSON.stringify(pr.b));
  const pid = pr.b.id;
  const b = await chromium.launch({ channel: 'msedge', headless: !process.env.HEADED });
  const ctx = await b.newContext({ viewport: { width: 1280, height: 860 }, colorScheme: 'dark' });
  const p = await ctx.newPage(); p.setDefaultTimeout(15000); const errs = []; p.on('pageerror', e => errs.push(e.message));
  await p.goto(BASE + '/auth/login'); await p.fill('#email', prod.email); await p.fill('#password', prod.pw); await p.click('button.submit-btn');
  await p.waitForURL(u => !u.pathname.startsWith('/auth'));
  if (p.url().includes('/consentement')) { await p.getByRole('radio', { name: /18 ans ou plus/i }).click(); await p.locator('.check input').check(); await p.getByRole('button', { name: /^Continuer/ }).click(); await p.waitForURL(u => !u.pathname.startsWith('/consentement')); }
  await p.goto(BASE + '/rooms/' + pid); await p.waitForTimeout(1500);
  await p.getByRole('tab', { name: /Équipe/ }).click().catch(async () => p.locator('button', { hasText: 'Équipe' }).first().click());
  await p.waitForTimeout(500);
  const mail = `recette.externe.${st}@exemple.tn`;
  await p.fill('form.invite input', mail); await p.locator('form.invite button').click(); await p.waitForTimeout(1200);
  ok(await p.locator('.ext').count() === 1, 'adresse inconnue : la room demande son rôle au lieu d’une erreur');
  ok(await p.locator('.err, [role=alert]').filter({ hasText: 'Aucun compte' }).count() === 0, 'plus de message « Aucun compte actif »');
  await p.locator('.kind', { hasText: 'Réalisateur' }).click();
  await p.getByRole('button', { name: "Créer le lien d'invitation" }).click();
  await p.locator('app-share-link input').waitFor();
  const link = await p.locator('app-share-link input').inputValue();
  ok(/invitation-pro\//.test(link), 'un lien d’invitation est prêt à envoyer');
  await p.screenshot({ path: path.join(OUT, 'room-invitation-externe.jpg'), type: 'jpeg', quality: 75 });
  const e = await (await b.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, colorScheme: 'dark' })).newPage();
  e.on('pageerror', x => errs.push(x.message));
  await e.goto(link.replace(/^https?:\/\/[^/]+/, BASE)); await e.waitForTimeout(1200);
  ok((await e.locator('h1').innerText()).includes('room'), 'la page d’invitation parle de la room');
  await e.fill('#fn', 'Ines'); await e.fill('#ln', 'Recette'); await e.getByRole('button', { name: 'Suivant' }).click();
  await e.fill('#pw', 'Rec3tte-' + st); await e.locator('.check input').check();
  await e.getByRole('button', { name: 'Rejoindre le projet' }).click();
  await e.waitForURL(new RegExp('/rooms/' + pid), { timeout: 15000 }); await e.waitForTimeout(1500);
  ok(true, 'la personne invitée arrive directement dans la room');
  await e.screenshot({ path: path.join(OUT, 'room-externe-arrivee.jpg'), type: 'jpeg', quality: 80 });
  await p.reload(); await p.waitForTimeout(1500);
  await p.locator('button', { hasText: 'Équipe' }).first().click(); await p.waitForTimeout(500);
  ok((await p.locator('.team').innerText()).includes('Ines Recette'), 'elle apparaît dans l’équipe de la room');
  ok(errs.length === 0, 'aucune erreur JavaScript' + (errs.length ? ' : ' + errs.join(' | ') : ''));
  await b.close();
})().catch(e => { console.error(e.stack || e.message); process.exit(1); });
